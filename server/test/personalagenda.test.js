import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
process.env.DATA_DIR=mkdtempSync(join(tmpdir(),'agenda-'));
const {db,setSetting}=await import('../src/db.js');
const {personalAgenda}=await import('../src/personalagenda.js');
const {lidarrSync}=await import('../src/lidarr.js');
test('Lidarr sin discos, seguimiento desde Radar y fechas de obra y recomendación independientes', async t=>{
  const mbid='00000000-0000-4000-8000-000000000001';
  setSetting('lidarr_url','http://lidarr.test');
  setSetting('lidarr_key','prueba');
  let monitored=true;
  t.mock.method(globalThis,'fetch',async url=>Response.json(url.endsWith('/artist') ?
    [{foreignArtistId:mbid,artistName:'Grupo sin discos',monitored}] : []));
  await lidarrSync();
  const now=new Date('2026-11-22T12:00:00Z');
  const a=personalAgenda(now).artists[0];
  assert.equal(a.name,'Grupo sin discos');
  db.prepare("INSERT INTO artists(id,name) VALUES (25,'Tom Waits')").run();
  db.prepare("INSERT INTO release_groups(rg_mbid,artist_id,title,primary_type,first_release) VALUES ('old',25,'Disco antiguo','Album','2008-09-01'),('new',?,'Nuevo EP','EP','2027-03')").run(a.id);
  db.prepare("INSERT INTO curators(id,username,source) VALUES (1,'revista','buymusicclub')").run();
  db.prepare("INSERT INTO radar_items(curator_id,artist,title,list_date,release_date) VALUES(1,'Tom Waits','Disco antiguo','2026-11-20','2008-09-01')").run();
  assert.equal(personalAgenda(now).mentions.length,0);
  db.prepare("INSERT INTO tracked_artists(artist_id,facet) VALUES (25,'artist')").run();
  const agenda=personalAgenda(now);
  assert.deepEqual(agenda.releases.map(r=>r.title),['Nuevo EP']);
  assert.equal(agenda.mentions[0].date,'2026-11-20');
  assert.equal(agenda.mentions[0].original,'2008-09-01');
  monitored=false;
  await lidarrSync();
  assert.deepEqual(personalAgenda(now).artists.map(a=>a.name),['Tom Waits']);
});
